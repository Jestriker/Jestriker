export const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

export const glyph = (ch) => FONT[ch.toUpperCase()] ?? FONT['?'];

export function textWidth(text, scale, gap = 1) {
  return [...text].length * (5 + gap) * scale - gap * scale;
}

// Render text as pixel rects. `perPixel(x, y, i, col)` may return extra attributes (for staggered animation).
export function pixelText(text, x0, y0, scale, { fill = '#fff', gap = 1, perPixel, cls = '' } = {}) {
  const out = [];
  let i = 0;
  [...text].forEach((ch, ci) => {
    const g = glyph(ch);
    const gx = x0 + ci * (5 + gap) * scale;
    g.forEach((row, ry) => {
      [...row].forEach((bit, rx) => {
        if (bit !== '1') return;
        const x = gx + rx * scale;
        const y = y0 + ry * scale;
        const extra = perPixel ? perPixel(x, y, i, ci * 5 + rx) : '';
        out.push(`<rect x="${x}" y="${y}" width="${scale}" height="${scale}" fill="${fill}"${cls ? ` class="${cls}"` : ''}${extra}/>`);
        i++;
      });
    });
  });
  return out.join('');
}

export function sprite(rows, x0, y0, scale, palette = SPRITE_PALETTE) {
  const out = [];
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === '.' || !palette[c]) return;
      out.push(`<rect x="${x0 + x * scale}" y="${y0 + y * scale}" width="${scale}" height="${scale}" fill="${palette[c]}"/>`);
    }),
  );
  return out.join('');
}

// Deterministic PRNG seeded from a string, so identicons and star fields are stable between builds.
export function rng(seed) {
  let h = 2166136261;
  for (const c of String(seed)) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return (h >>> 0) / 4294967296;
  };
}

// Symmetric 8x8 identicon, used when a tool doesn't define its own sprite.
export function identicon(seed) {
  const r = rng(seed);
  const rows = [];
  for (let y = 0; y < 8; y++) {
    const half = Array.from({ length: 4 }, () => (r() > 0.45 ? (r() > 0.75 ? '2' : '1') : '.'));
    rows.push(half.join('') + [...half].reverse().join(''));
  }
  return rows;
}
